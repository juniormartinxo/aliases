//! `aliases init <shell>`: the code a shell evaluates to get the aliases and the
//! `alias-*` commands. A program cannot change its parent shell, so the shell runs
//! this output itself (`eval "$(aliases init zsh)"`).

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::Path;

use crate::Shell;
use crate::alias_file::{AliasFile, shell_quote};

/// Definitions in load order, without repeated names: like the shell, the last one wins.
fn effective(files: &[AliasFile]) -> Vec<(&str, &str, &str)> {
    let mut seen = HashSet::new();
    let definitions: Vec<_> = files.iter().flat_map(|f| f.definitions()).collect();
    let mut all: Vec<_> = definitions
        .into_iter()
        .rev()
        .filter(|d| seen.insert(d.name.as_str()))
        .map(|d| (d.name.as_str(), d.value.as_str(), d.raw_value.as_str()))
        .collect();
    all.reverse();
    all
}

pub fn render(shell: Shell, bin: &Path, files: &[AliasFile], aliases_only: bool) -> String {
    match shell {
        Shell::Bash | Shell::Zsh => posix(shell, bin, files, aliases_only),
        Shell::Pwsh => pwsh(bin, files, aliases_only),
    }
}

const POSIX_FUNCTIONS: &str = r#"
_aliases_manager_run() {
    ALIASES_MANAGER_WRAPPED=1 "$_aliases_manager_bin" "$@"
}

alias-reload() {
    eval "$("$_aliases_manager_bin" init @SHELL@ --aliases-only)" || return
    case "${1-}" in
        -q|--quiet) ;;
        *) echo "Aliases reloaded!" ;;
    esac
}

alias-create() { _aliases_manager_run create "$@" && alias-reload --quiet; }
alias-remove() { _aliases_manager_run remove "$@" && alias-reload --quiet; }
alias-edit() { _aliases_manager_run edit "$@" && alias-reload --quiet; }
alias-enable() { _aliases_manager_run enable "$@" && alias-reload --quiet; }
alias-disable() { _aliases_manager_run disable "$@" && alias-reload --quiet; }
alias-list() { "$_aliases_manager_bin" list "$@"; }
alias-find() { "$_aliases_manager_bin" find "$@"; }
alias-doctor() { "$_aliases_manager_bin" doctor --shell @SHELL@ "$@"; }
"#;

fn posix(shell: Shell, bin: &Path, files: &[AliasFile], aliases_only: bool) -> String {
    let mut out = String::new();
    if !aliases_only {
        let _ = writeln!(out, "# Generated by `aliases init {}`.", shell.name());
        let _ = writeln!(
            out,
            "_aliases_manager_bin={}",
            shell_quote(&bin.to_string_lossy())
        );
        out.push_str(&POSIX_FUNCTIONS.replace("@SHELL@", shell.name()));
        out.push('\n');
    }

    // Drop the aliases of the previous load, so removed ones disappear on reload.
    let previous = match shell {
        Shell::Zsh => "${=_aliases_manager_loaded}",
        _ => "${_aliases_manager_loaded-}",
    };
    let _ = writeln!(out, "for _aliases_manager_name in {previous}; do");
    out.push_str("    unalias \"$_aliases_manager_name\" 2>/dev/null\n");
    out.push_str("done\nunset _aliases_manager_name\n");

    let definitions = effective(files);
    for (name, _, raw) in &definitions {
        let _ = writeln!(out, "alias {name}={raw}");
    }
    let names: Vec<_> = definitions.iter().map(|(name, _, _)| *name).collect();
    let _ = writeln!(
        out,
        "_aliases_manager_loaded={}",
        shell_quote(&names.join(" "))
    );
    out
}

/// PowerShell function names: the subset of alias names that `function` accepts and
/// that does not read as something else on the command line.
pub fn is_pwsh_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

/// A PowerShell expression for `text` that is plain ASCII, so it survives whatever
/// encoding PowerShell uses to read this program's output.
pub fn pwsh_string(text: &str) -> String {
    if text.is_ascii() {
        return format!("'{}'", text.replace('\'', "''"));
    }
    let mut parts = vec!["''".to_string()];
    let mut run = String::new();
    for c in text.chars() {
        if c.is_ascii() {
            run.push(c);
            continue;
        }
        if !run.is_empty() {
            parts.push(format!("'{}'", run.replace('\'', "''")));
            run.clear();
        }
        let code = u32::from(c);
        parts.push(if code <= 0xFFFF {
            format!("[char]0x{code:04X}")
        } else {
            format!("[char]::ConvertFromUtf32(0x{code:X})")
        });
    }
    if !run.is_empty() {
        parts.push(format!("'{}'", run.replace('\'', "''")));
    }
    format!("({})", parts.join(" + "))
}

const PWSH_FUNCTIONS: &str = r#"
function global:_aliases_manager_quote_argument {
    param([Parameter(Mandatory)][AllowEmptyString()][string]$Value)

    return "'" + $Value.Replace("'", "''") + "'"
}

function global:_aliases_manager_invoke_alias_command {
    param(
        [Parameter(Mandatory)][string]$Command,
        [object[]]$Arguments = @()
    )

    $argumentList = @($Arguments | Where-Object { $null -ne $_ })
    $invocation = $Command

    if ($argumentList.Count -gt 0) {
        $quotedArguments = @($argumentList | ForEach-Object {
                _aliases_manager_quote_argument -Value ([string]$_)
            })
        $invocation = "$Command $($quotedArguments -join ' ')"
    }

    if ($invocation -match '^(?<path>[A-Za-z]:\\.*?\.(?:exe|cmd|bat|com|ps1|psm1))(?<rest>(?:\s+.*)?)$') {
        $escapedPath = $matches['path'].Replace("'", "''")
        $invocation = "& '$escapedPath'$($matches['rest'])"
    }

    Invoke-Expression $invocation
}

# Removes the functions of the previous load. Get-Variable -ValueOnly returns the list as
# a single object, so it must not be wrapped in @() before enumerating it.
function global:_aliases_manager_unload {
    foreach ($name in (Get-Variable -Name ALIASES_LOADED -Scope Global -ValueOnly -ErrorAction SilentlyContinue)) {
        if ($name) { Remove-Item -LiteralPath "Function:\$name" -Force -ErrorAction SilentlyContinue }
    }
}

# PowerShell-style -Help becomes the --help the aliases program understands.
function global:_aliases_manager_args {
    foreach ($argument in $args) {
        if ($argument -is [string] -and $argument -eq '-Help') { '--help' } else { $argument }
    }
}

function global:_aliases_manager_run {
    $env:ALIASES_MANAGER_WRAPPED = '1'
    try {
        & $global:ALIASES_MANAGER_BIN @args
    }
    finally {
        Remove-Item Env:\ALIASES_MANAGER_WRAPPED -ErrorAction SilentlyContinue
    }
}

function global:alias-reload {
    param([switch]$Quiet, [Alias('h')][switch]$Help)

    if ($Help) {
        Write-Host "Usage: alias-reload [-Quiet]`n`nReloads all managed aliases into the current PowerShell session."
        return
    }

    $script = & $global:ALIASES_MANAGER_BIN init pwsh --aliases-only | Out-String
    if ($LASTEXITCODE -ne 0) { return }
    Invoke-Expression $script
    if (-not $Quiet) { Write-Host 'Aliases reloaded!' -ForegroundColor Green }
}

function global:alias-create { _aliases_manager_run create @(_aliases_manager_args @args); if ($LASTEXITCODE -eq 0) { alias-reload -Quiet } }
function global:alias-remove { _aliases_manager_run remove @(_aliases_manager_args @args); if ($LASTEXITCODE -eq 0) { alias-reload -Quiet } }
function global:alias-edit { _aliases_manager_run edit @(_aliases_manager_args @args); if ($LASTEXITCODE -eq 0) { alias-reload -Quiet } }
function global:alias-enable { _aliases_manager_run enable @(_aliases_manager_args @args); if ($LASTEXITCODE -eq 0) { alias-reload -Quiet } }
function global:alias-disable { _aliases_manager_run disable @(_aliases_manager_args @args); if ($LASTEXITCODE -eq 0) { alias-reload -Quiet } }
function global:alias-list { & $global:ALIASES_MANAGER_BIN list @(_aliases_manager_args @args) }
function global:alias-find { & $global:ALIASES_MANAGER_BIN find @(_aliases_manager_args @args) }
function global:alias-doctor { & $global:ALIASES_MANAGER_BIN doctor --shell pwsh --rc $PROFILE @(_aliases_manager_args @args) }
"#;

fn pwsh(bin: &Path, files: &[AliasFile], aliases_only: bool) -> String {
    let mut out = String::new();
    if !aliases_only {
        out.push_str("# Generated by `aliases init pwsh`.\n");
        let _ = writeln!(
            out,
            "$global:ALIASES_MANAGER_BIN = {}",
            pwsh_string(&bin.to_string_lossy())
        );
        out.push_str(PWSH_FUNCTIONS);
        out.push('\n');
    }

    // Drop the functions of the previous load, so removed aliases disappear on reload.
    out.push_str("_aliases_manager_unload\n");

    let definitions: Vec<_> = effective(files)
        .into_iter()
        .filter(|(name, _, _)| is_pwsh_name(name))
        .collect();
    for (name, value, _) in &definitions {
        let _ = writeln!(
            out,
            "function global:{name} {{ _aliases_manager_invoke_alias_command -Command {} -Arguments $args }}",
            pwsh_string(value)
        );
    }
    let names: Vec<_> = definitions
        .iter()
        .map(|(name, _, _)| pwsh_string(name))
        .collect();
    let _ = writeln!(out, "$global:ALIASES_LOADED = @({})", names.join(", "));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pwsh_strings_are_ascii() {
        assert_eq!(pwsh_string("it's"), "'it''s'");
        assert_eq!(pwsh_string("ãb'"), "('' + [char]0x00E3 + 'b''')");
        assert_eq!(
            pwsh_string("a😀"),
            "('' + 'a' + [char]::ConvertFromUtf32(0x1F600))"
        );
    }

    #[test]
    fn pwsh_names() {
        assert!(is_pwsh_name("docker-up"));
        assert!(is_pwsh_name("_x1"));
        assert!(!is_pwsh_name(".."));
        assert!(!is_pwsh_name("7z"));
        assert!(!is_pwsh_name("a.b"));
    }
}
